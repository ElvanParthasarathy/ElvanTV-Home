    /**
     * Rebuilds the tiles. A shown module card stands in for every tile of its package (same component,
     * so focus follows it); hidden_apps wins over a card, and a card's package in dock_apps takes that slot.
     */
    void reload(List<Cards.Card> cards, List<ResolveInfo> leanback) {
        PackageManager pm = ctx.getPackageManager();
        // The LEANBACK query is shared with the module-card check (MainActivity); copy it before adding
        // library apps so the caller's list stays as it was.
        List<ResolveInfo> found = new ArrayList<>(leanback);
        Set<String> tvPackages = new HashSet<>();
        for (ResolveInfo ri : found) if (ri.activityInfo != null) tvPackages.add(ri.activityInfo.packageName);
        leanbackPackages = tvPackages;
        // Copy before merging: LibraryApps.load() may return an immutable empty set (#419).
        Set<String> added = new HashSet<>(LibraryApps.load(ctx));
        added.addAll(libraryPreload);
        Set<String> removed = LibraryApps.loadRemoved(ctx);
        if (!added.isEmpty()) {
            Set<String> seen = new HashSet<>(tvPackages);
            for (ResolveInfo ri : pm.queryIntentActivities(
                    new Intent(Intent.ACTION_MAIN).addCategory(Intent.CATEGORY_LAUNCHER), 0)) {
                if (ri.activityInfo != null && added.contains(ri.activityInfo.packageName)
                        && seen.add(ri.activityInfo.packageName)) found.add(ri);
            }
        }
        Map<String, Cards.Card> cardByPkg = new HashMap<>();
        for (Cards.Card c : cards) cardByPkg.put(c.pkg, c);
        List<Entry> fresh = new ArrayList<>();
        // Some system apps declare two leanback entry points under one name (Sony's Timers & Clock on the
        // BRAVIA VU31), which would show as two identical tiles: keep the first per package and label.
        Set<String> seen = new HashSet<>();
        for (ResolveInfo ri : found) {
            if (ri.activityInfo == null) continue;
            String pkg = ri.activityInfo.packageName;
            if (pkg.equals(ctx.getPackageName()) || !ri.activityInfo.exported
                    || !LibraryApps.visible(tvPackages.contains(pkg), hidden.contains(pkg), added.contains(pkg), removed.contains(pkg))) continue;
            ComponentName component = new ComponentName(pkg, ri.activityInfo.name);
            Cards.Card card = cardByPkg.get(pkg);
            if (card != null && !card.component.equals(component)) continue;   // the card stands in for this tile
            // Same cleaner as the card prompt: an app label with a bidi override or line separator must not
            // redraw the tile name as something else (#117).
            String label = card != null ? card.label : Cards.cleanLabel(
                    appLabels.containsKey(pkg) ? appLabels.get(pkg) : String.valueOf(ri.loadLabel(pm)), pkg);
            if (!seen.add(pkg + '\n' + label)) continue;
            Drawable icon = ri.loadIcon(pm);
            if (icon == null) {
                try {
                    icon = pm.getApplicationIcon(pkg);
                } catch (Exception ignored) {}
            }
            icon = IconNormalizer.normalize(ctx, icon);
            if (card != null) {
                fresh.add(new Entry(Entry.CARD, label, component, null, icon, card.caption, card.accent));
            } else {
                fresh.add(new Entry(label, component, null, icon));
            }
        }
        Collections.sort(fresh, (a, b) -> {
            // The owner's own order first; tiles it does not know (new installs) follow by the rule below.
            int saved = Order.compare(savedRanks, a.component.flattenToShortString(), b.component.flattenToShortString());
            if (saved != 0) return saved;
            int fa = favourites.indexOf(a.pkg), fb = favourites.indexOf(b.pkg);
            if (fa >= 0 || fb >= 0) {
                if (fa < 0) return 1;
                if (fb < 0) return -1;
                return Integer.compare(fa, fb);
            }
            // Cards come right after the configured dock apps, before the alphabetical grid.
            boolean ca = a.kind == Entry.CARD, cb = b.kind == Entry.CARD;
            if (ca != cb) return ca ? -1 : 1;
            return a.label.compareToIgnoreCase(b.label);
        });
        // Retain the optional Default-home tile until dependent tile-ordering work is merged.
        if (showHomeSettings
                && pm.resolveActivity(new Intent(Settings.ACTION_HOME_SETTINGS), 0) != null) {
            fresh.add(new Entry(Entry.HOME_SETTINGS, ctx.getString(R.string.home_settings),
                    new ComponentName(ctx, HomeSettingsActivity.class), null,
                    IconNormalizer.normalize(ctx, ctx.getDrawable(R.drawable.ic_home_settings)), null, 0));
        }
        docked = 0;
        emptySlots = 0;
        items.clear();
        items.addAll(fresh);
        notifyDataSetChanged();
    }

    /** A banner_* drawable bundled with the launcher, or null for none or a name that is not one. */
    private Drawable bundledBanner(String name) {
        if (name == null || !name.startsWith("banner_")) return null;
        int id = ctx.getResources().getIdentifier(name, "drawable", ctx.getPackageName());
        return id != 0 ? ctx.getDrawable(id) : null;
    }

    private Drawable loadBanner(PackageManager pm, ResolveInfo ri) {
        int id = ri.activityInfo.banner;
        if (id == 0) id = ri.activityInfo.applicationInfo.banner;
        Drawable banner = null;
        if (id != 0) {
            try {
                Resources resources = pm.getResourcesForApplication(ri.activityInfo.applicationInfo);
                // Keep at least xhdpi detail rather than downsampling artwork before the focus zoom.
                int density = Math.max(DisplayMetrics.DENSITY_XHIGH, ctx.getResources().getDisplayMetrics().densityDpi);
                banner = resources.getDrawableForDensity(id, density, null);
            } catch (PackageManager.NameNotFoundException | Resources.NotFoundException ignored) {
            }
        }
        if (banner == null) banner = ri.activityInfo.loadBanner(pm);
        // A square "banner" counts as none: the tile shows the app's icon and name instead of a blur.
        return banner != null && isBannerShaped(banner.getIntrinsicWidth(), banner.getIntrinsicHeight()) ? banner : null;
    }

    /**
     * Some apps declare a small square image as their banner (Rockchip's Media Center ships a 64 px one). Cropped
     * over a 16:9 tile it is a blur. A drawable with no intrinsic size (a colour, a shape) still fills the tile.
     */
    static boolean isBannerShaped(int width, int height) {
        return width <= 0 || height <= 0 || width >= height * 1.4f;
    }

    /** Lets go of every tile and its artwork (Home is in the background and memory is short). */
    void clear() {
        items.clear();
        notifyDataSetChanged();
    }

    @NonNull
    @Override
    public RecyclerView.ViewHolder onCreateViewHolder(@NonNull ViewGroup parent, int viewType) {
        if (viewType == 2) {
            View v = LayoutInflater.from(parent.getContext()).inflate(R.layout.item_reorder_tile, parent, false);
            return new ReorderHolder(v, listener, animations, advancedEffects, reducedMotion);
        }
        if (viewType == 1) {
            View row = LayoutInflater.from(ctx).inflate(R.layout.row_app_library, parent, false);
            View button = row.findViewById(R.id.btnLibrary);
            button.setOnClickListener(v -> listener.onLibraryRequested());
            button.setOnFocusChangeListener((v, focused) -> { if (focused) listener.onLibraryFocused(); });
            button.setOnKeyListener((v, key, event) -> {
                if (event.getAction() != KeyEvent.ACTION_DOWN) return false;
                if (key == KeyEvent.KEYCODE_DPAD_UP) listener.onLibraryUp();
                return key == KeyEvent.KEYCODE_DPAD_UP || key == KeyEvent.KEYCODE_DPAD_DOWN
                        || key == KeyEvent.KEYCODE_DPAD_LEFT || key == KeyEvent.KEYCODE_DPAD_RIGHT;
            });
            return new RecyclerView.ViewHolder(row) { };
        }
        View v = LayoutInflater.from(parent.getContext()).inflate(R.layout.item_app, parent, false);
        return new Holder(v, listener, animations, advancedEffects, reducedMotion, restNameAlpha, focusOvershoot);
    }

    @Override
    public void onBindViewHolder(@NonNull RecyclerView.ViewHolder holder, int position) {
        if (isReorderAt(position)) {
            ReorderHolder rh = (ReorderHolder) holder;
            rh.name.setText(R.string.reorder);
            // Stays on screen, dimmed, while the apps are rearranged, as on the stock launcher.
            rh.card.setFocusable(!reordering);
            boolean focused = rh.card.isFocused();
            rh.card.setScaleX(focused && animations ? 1.06f : 1f);
            rh.card.setScaleY(focused && animations ? 1.06f : 1f);
            rh.icon.setColorFilter(focused ? 0xFF1F1F21 : 0xFFFFFFFF);
            rh.name.setTextColor(focused ? 0xFF1F1F21 : 0xFFFFFFFF);
            rh.name.setAlpha(focused ? 1f : 0.85f);
            return;
        }
        if (isLibraryAt(position)) return;
        Holder h = (Holder) holder;
        Entry e = items.get(position);
        if (e.kind == Entry.EMPTY) {
            h.card.setVisibility(View.INVISIBLE);
            h.card.setFocusable(false);
            h.name.setVisibility(View.INVISIBLE);
            h.banner.setImageDrawable(null);
            h.icon.setImageDrawable(null);
            h.card.setOnClickListener(null);
            h.card.setOnLongClickListener(null);
            return;
        }
        h.card.setVisibility(View.VISIBLE);
        h.card.setFocusable(true);
        h.name.setText(e.name);
        h.name.setVisibility(View.VISIBLE);
        boolean focused = h.card.isFocused();
        h.name.setAlpha(focused ? 1f : restNameAlpha);
        h.name.setEllipsize(focused ? TextUtils.TruncateAt.MARQUEE : TextUtils.TruncateAt.END);
        TitleScroller.set(h.name, focused);
        h.card.setScaleX(focused && animations ? focusScale() : 1f);
        h.card.setScaleY(focused && animations ? focusScale() : 1f);
        if (h.focusRing != null) {
            if (focused) {
                h.focusRing.setVisibility(View.VISIBLE);
                h.focusRing.setAlpha(1f);
                h.stopRingBreathing();
                if (animations && !reducedMotion && !Motion.lowEnd) {
                    h.card.postDelayed(h.breathingRunnable, Holder.DWELL_BREATHING_DELAY_MS);
                }
            } else {
                h.stopRingBreathing();
                h.focusRing.setVisibility(View.GONE);
            }
        }
        if (h.reorderPrompt != null) {
            if (reordering && focused) {
                boolean isMovingThis = movingKey != null && movingKey.equals(keyAt(position));
                h.reorderPrompt.setVisibility(View.VISIBLE);
                h.reorderPrompt.setText(isMovingThis ? R.string.press_to_confirm : R.string.press_to_move);
            } else {
                // Reserved while reordering, so the row (and the Done button under it) never changes height.
                h.reorderPrompt.setVisibility(reordering ? View.INVISIBLE : View.GONE);
            }
        }
        h.banner.setVisibility(View.GONE);
        h.icon.setImageDrawable(e.icon);
        h.icon.setVisibility(View.VISIBLE);
        h.label.setVisibility(View.GONE);
        h.card.setOnClickListener(v -> launch(e));
        h.card.setOnLongClickListener(v -> {
            if (tileMenu) {
                int pos = h.getBindingAdapterPosition();
                if (pos != RecyclerView.NO_POSITION) listener.onTileLongPress(pos, v);
                return true;
            }
            Intent i = new Intent(Settings.ACTION_APPLICATION_DETAILS_SETTINGS, Uri.parse("package:" + e.pkg));
            i.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK);
            try {
                ctx.startActivity(i);
            } catch (ActivityNotFoundException ignored) {
            }
            return true;
        });
    }

    void open(Entry e) {
        launch(e);
    }

    /** Opens the tile's activity by explicit component, with no extras: a card can name nothing else. */
    private void launch(Entry e) {
        if (e.kind == Entry.HOME_SETTINGS) {
            ctx.startActivity(new Intent(ctx, HomeSettingsActivity.class)
                    .addFlags(Intent.FLAG_ACTIVITY_NEW_TASK));
            return;
        }
        Intent i = new Intent(Intent.ACTION_MAIN)
                .setComponent(e.component)
                .addFlags(Intent.FLAG_ACTIVITY_NEW_TASK | Intent.FLAG_ACTIVITY_RESET_TASK_IF_NEEDED);
        // TV apps launch with the same leanback intent as from the stock launcher or the remote, so an app
        // already running resumes instead of restarting; only phone apps added from the library use plain MAIN.
        if (leanbackPackages.contains(e.pkg)) i.addCategory(Intent.CATEGORY_LEANBACK_LAUNCHER);
        String action = launchActions.get(e.pkg);
        if (action != null) {
            // NEW_TASK only: with RESET_TASK_IF_NEEDED, Android just brings a running task of the app to the front
            // ("Activity not started"), so the screen never opens while the app is up, e.g. MagentaTV's boot-time task.
            Intent byAction = new Intent(action).setPackage(e.pkg).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK);
            if (ctx.getPackageManager().resolveActivity(byAction, 0) != null) i = byAction;
        }
        try {
            ctx.startActivity(i);
            LastOpened.record(ctx, e.pkg);
            if (advancedEffects && !reducedMotion && ctx instanceof Activity) {
                ((Activity) ctx).overridePendingTransition(R.anim.app_open_enter, R.anim.app_open_exit);
            }
        } catch (Exception ex) {
            Toast.makeText(ctx, ctx.getString(R.string.cant_open, e.label), Toast.LENGTH_SHORT).show();
        }
    }

    boolean isReorderAt(int position) {
        return items.size() > 1 && position == items.size();
    }

    boolean isLibraryAt(int position) {
        if (reordering || !showLibrary) return false;
        int reorderOffset = items.size() > 1 ? 1 : 0;
        return position == items.size() + reorderOffset;
    }

    @Override
    public int getItemCount() {
        if (reordering) return items.size() + (items.size() > 1 ? 1 : 0);
        return items.size() + (items.size() > 1 ? 1 : 0) + (showLibrary ? 1 : 0);
    }

    int appCount() { return items.size(); }

    @Override
    public int getItemViewType(int position) {
        if (isReorderAt(position)) return 2;
        if (isLibraryAt(position)) return 1;
        return 0;
    }

    boolean containsPackage(String pkg) {
        for (Entry entry : items) if (entry.pkg.equals(pkg)) return true;
        return false;
    }

    @Override
    public long getItemId(int position) {
        if (isReorderAt(position)) return Long.MIN_VALUE + 1;
        if (isLibraryAt(position)) return Long.MIN_VALUE;
        return items.get(position).component.flattenToShortString().hashCode();
    }

    /** Uses this saved order and dock size from the next reload() (Order.ranks, Order.docked). */
    void setSavedOrder(Map<String, Integer> ranks, int docked) {
        savedRanks = ranks;
        savedDocked = docked;
    }

    /**
     * A tile in the dock: one of the first savedDocked tiles of the saved order when one was recorded, so an app
     * the owner moved into the dock stays there (#499); else a dock_apps entry.
     */
    private boolean isDocked(Entry e) {
        if (savedDocked < 0) return favourites.contains(e.pkg);
        Integer rank = savedRanks.get(e.component.flattenToShortString());
        return rank != null && rank < savedDocked;
    }

    /** Reorder mode on or off; takes effect at the next reload() (empty dock slots are left out while on). */
    void setReordering(boolean on) {
        if (reordering == on) return;
        int before = getItemCount();
        reordering = on;
        if (!on) movingKey = null;
        int after = getItemCount();
        // No rebuild and no rebind of the tiles on screen: either drops the focused view for a frame or two, and the
        // ring and glow flicker. MainActivity updates the tiles on screen in place and asks for the rest to be
        // rebound. Only the library tile, which reorder mode leaves out, comes or goes.
        if (after < before) notifyItemRangeRemoved(after, before - after);
        else if (after > before) notifyItemRangeInserted(before, after - before);
    }

    void setMovingKey(String key) {
        movingKey = key;
    }

    boolean hasEmptySlots() {
        return emptySlots > 0;
    }

    /** Tiles that can be moved: everything but the "Default home" tile, which always stays last. */
    int movableCount() {
        int n = items.size();
        return n > 0 && items.get(n - 1).kind == Entry.HOME_SETTINGS ? n - 1 : n;
    }

    /** Keys of the movable tiles in their current order, for Order (empty dock slots are not tiles). */
    List<String> movableKeys() {
        List<String> keys = new ArrayList<>();
        for (int i = 0; i < movableCount(); i++) {
            Entry e = items.get(i);
            if (e.kind != Entry.EMPTY) keys.add(e.component.flattenToShortString());
        }
        return keys;
    }

    /** Moves one tile; the others shift by one. Stable ids keep the moved tile's view (and its focus). */
    void move(int from, int to) {
        if (from == to || from < 0 || to < 0 || from >= movableCount() || to >= movableCount()) return;
        items.add(to, items.remove(from));
        notifyItemMoved(from, to);
        // The dock row hides names by position: rebind the tiles whose side of the dock edge changed.
        if (from < dockSize || to < dockSize) {
            int lo = Math.min(from, to), hi = Math.max(from, to);
            notifyItemRangeChanged(lo, hi - lo + 1);
        }
    }

    /** Stable key for the app at a position (its component), or null. */
    String keyAt(int position) {
        return position >= 0 && position < items.size() ? items.get(position).component.flattenToShortString() : null;
    }

    /** Position of the app with this key, or -1 when it is gone. */
    int positionOf(String key) {
        if (key == null) return -1;
        for (int i = 0; i < items.size(); i++) {
            if (items.get(i).component.flattenToShortString().equals(key)) return i;
        }
        return -1;
    }

    /** Dock slots that hold an app: the whole dock unless some slots are empty. */
    int dockFilled() {
        return emptySlots > 0 ? docked : dockSize;
    }

    /** A position focus can land on: an empty dock slot gives the last dock app. */
    int focusablePosition(int position) {
        return DockSlots.focusable(position, docked, emptySlots);
    }

    String labelAt(int position) {
        if (isReorderAt(position)) return ctx.getString(R.string.reorder);
        return position >= 0 && position < items.size() ? items.get(position).label : "";
    }

    String packageAt(int position) {
        return position >= 0 && position < items.size() ? items.get(position).pkg : null;
    }

    /** The tile's artwork, its banner or else its icon, for the cinematic shelf's backdrop (HeroArt). */
    Drawable artworkAt(int position) {
        if (position < 0 || position >= items.size()) return null;
        Entry e = items.get(position);
        return e.banner != null ? e.banner : e.icon;
    }

    float focusScale() {
        return !animations ? 1f : advancedEffects ? 1.12f : 1.10f;
    }

    /** A vivid colour sampled from the app's banner (or icon), cached per entry; a card's accent when it set one. */
    int ambientColorAt(int position) {
        if (isReorderAt(position)) return 0xFF666666;
        if (position < 0 || position >= items.size()) return 0xFF444444;
        Entry e = items.get(position);
        if (e.ambient == 0) e.ambient = vividColor(e.banner != null ? e.banner : e.icon);
        return e.ambient;
    }

    private static int vividColor(Drawable live) {
        if (live == null) return 0xFF444444;
        // Draw a private copy: changing the bounds of the drawable an ImageView shows would blank the tile.
        Drawable d = live.getConstantState() != null ? live.getConstantState().newDrawable().mutate() : live;
        Rect saved = new Rect(d.getBounds());
        int n = 12;
        Bitmap bmp = Bitmap.createBitmap(n, n, Bitmap.Config.ARGB_8888);
        Canvas c = new Canvas(bmp);
        d.setBounds(0, 0, n, n);
        d.draw(c);
        d.setBounds(saved);
        int[] px = new int[n * n];
        bmp.getPixels(px, 0, n, 0, 0, n, n);
        bmp.recycle();
        float[] hsv = new float[3];
        int best = 0xFF444444;
        float bestScore = -1f;
        long r = 0, g = 0, b = 0;
        for (int p : px) {
            int pr = (p >> 16) & 0xFF, pg = (p >> 8) & 0xFF, pb = p & 0xFF;
            r += pr;
            g += pg;
            b += pb;
            int max = Math.max(pr, Math.max(pg, pb));
            int min = Math.min(pr, Math.min(pg, pb));
            float sat = max == 0 ? 0f : (max - min) / (float) max;
            float val = max / 255f;
            float score = sat * Math.min(1f, val * 1.4f);   // saturated and not too dark
            if (score > bestScore) {
                bestScore = score;
                best = p;
            }
        }
        if (bestScore < 0.25f) {   // nearly monochrome banner (e.g. white): use its average, lifted
            int avg = Color.rgb((int) (r / (n * n)), (int) (g / (n * n)), (int) (b / (n * n)));
            Color.colorToHSV(avg, hsv);
            hsv[2] = Math.max(hsv[2], 0.55f);
            return Color.HSVToColor(hsv);
        }
        Color.colorToHSV(best, hsv);
        hsv[1] = Math.min(1f, hsv[1] * 1.1f);
        hsv[2] = Math.max(0.5f, hsv[2]);
        return Color.HSVToColor(hsv);
    }

    /** Corner radius for a tile of this width: 16dp at the design width, proportionally less when smaller. */
    static float cornerRadius(int tileWidthPx, float density) {
        return 16f * density * Math.min(1f, tileWidthPx / (DESIGN_W_DP * density));
    }

    @Override
    public void onViewRecycled(@NonNull RecyclerView.ViewHolder holder) {
        super.onViewRecycled(holder);
        if (holder instanceof Holder) {
            ((Holder) holder).stopRingBreathing();
        }
    }

    static final class Holder extends RecyclerView.ViewHolder {
        final View card;
        final Drawable cardBackground;
        final ImageView banner;
        final ImageView icon;
        final TextView label;
        final TextView name;
        final TextView reorderPrompt;
        final View focusRing;
        final boolean animations;
        final boolean advancedEffects;
        final boolean reducedMotion;
        final float restNameAlpha;
        final boolean overshoot;
        private android.animation.ValueAnimator ringAnimator;
        private final Runnable breathingRunnable = this::startRingBreathing;
        private static final long DWELL_BREATHING_DELAY_MS = 750;
        private static final long FOCUS_MS = 150;

        void startRingBreathing() {
            if (!animations || reducedMotion || Motion.lowEnd || focusRing == null || !card.isFocused()) return;
            if (ringAnimator != null) {
                ringAnimator.cancel();
            }
            focusRing.setAlpha(1.0f);
            ringAnimator = android.animation.ValueAnimator.ofFloat(1.0f, 0.40f);
            ringAnimator.setDuration(1400);
            ringAnimator.setRepeatMode(android.animation.ValueAnimator.REVERSE);
            ringAnimator.setRepeatCount(android.animation.ValueAnimator.INFINITE);
            ringAnimator.setInterpolator(new android.view.animation.AccelerateDecelerateInterpolator());
            ringAnimator.addUpdateListener(anim -> {
                if (focusRing != null) {
                    focusRing.setAlpha((float) anim.getAnimatedValue());
                }
            });
            ringAnimator.start();
        }

        void stopRingBreathing() {
            if (card != null) {
                card.removeCallbacks(breathingRunnable);
            }
            if (ringAnimator != null) {
                ringAnimator.cancel();
                ringAnimator = null;
            }
            if (focusRing != null) {
                focusRing.setAlpha(1f);
            }
        }

        Holder(View v, TileListener listener, boolean animations, boolean advancedEffects,
               boolean reducedMotion, float restNameAlpha, boolean overshoot) {
            super(v);
            card = v.findViewById(R.id.card);
            cardBackground = card.getBackground();
            banner = v.findViewById(R.id.banner);
            icon = v.findViewById(R.id.icon);
            label = v.findViewById(R.id.label);
            name = v.findViewById(R.id.name);
            reorderPrompt = v.findViewById(R.id.reorderPrompt);
            focusRing = v.findViewById(R.id.focusRing);
            this.animations = animations;
            this.advancedEffects = advancedEffects;
            this.reducedMotion = reducedMotion;
            this.restNameAlpha = restNameAlpha;
            this.overshoot = overshoot;

            final View iconFrame = v.findViewById(R.id.iconFrame);
            if (iconFrame != null) {
                iconFrame.setOutlineProvider(new ViewOutlineProvider() {
                    @Override
                    public void getOutline(View view, Outline outline) {
                        outline.setOval(0, 0, view.getWidth(), view.getHeight());
                    }
                });
                iconFrame.setClipToOutline(true);
            }

            card.setOnKeyListener((view, keyCode, event) -> {
                if (event.getAction() != KeyEvent.ACTION_DOWN) return false;
                if (keyCode != KeyEvent.KEYCODE_DPAD_UP && keyCode != KeyEvent.KEYCODE_DPAD_DOWN
                        && keyCode != KeyEvent.KEYCODE_DPAD_LEFT && keyCode != KeyEvent.KEYCODE_DPAD_RIGHT) return false;
                int pos = getBindingAdapterPosition();
                return listener != null && pos != RecyclerView.NO_POSITION && listener.onTileVerticalKey(pos, keyCode);
            });

            card.setOnFocusChangeListener((view, focused) -> {
                view.animate().cancel();
                name.animate().cancel();
                TitleScroller.set(name, focused);
                if (focusRing != null) {
                    focusRing.animate().cancel();
                    if (focused) {
                        stopRingBreathing();
                        focusRing.setVisibility(View.VISIBLE);
                        if (animations && !reducedMotion && !Motion.lowEnd) {
                            // Measured against the stock Google TV launcher: the focus move settles in ~150 ms.
                            focusRing.setAlpha(0f);
                            focusRing.animate().alpha(1f).setDuration(FOCUS_MS).start();
                            card.postDelayed(breathingRunnable, DWELL_BREATHING_DELAY_MS);
                        } else {
                            focusRing.setAlpha(1f);
                        }
                    } else {
                        stopRingBreathing();
                        focusRing.setVisibility(View.GONE);
                    }
                }
                float scale = !animations ? 1f : 1.11f;
                float s = focused ? scale : 1f;
                if (!animations) {
                    view.setScaleX(1f);
                    view.setScaleY(1f);
                    name.setAlpha(focused ? 1f : restNameAlpha);
                } else if (reducedMotion) {
                    view.animate().scaleX(s).scaleY(s)
                            .setDuration(focused ? Motion.REDUCED_MS : 60)
                            .setInterpolator(new DecelerateInterpolator())
                            .start();
                    name.setAlpha(focused ? 1f : restNameAlpha);
                } else {
                    android.view.ViewPropertyAnimator zoom = view.animate().scaleX(s).scaleY(s)
                            .setDuration(FOCUS_MS)
                            .setInterpolator(new DecelerateInterpolator(1f));
                    // A hardware layer for a 150 ms zoom is built and torn down on every focus move: on a weak GPU
                    // that was the one slow frame per key press.
                    if (!Motion.lowEnd) zoom.withLayer();
                    zoom.start();
                    name.animate().alpha(focused ? 1f : restNameAlpha)
                            .setDuration(FOCUS_MS).start();
                }
                int pos = getBindingAdapterPosition();
                if (focused && listener != null && pos != RecyclerView.NO_POSITION) {
                    listener.onTileFocused(pos, view);
                }
            });
        }
    }

    static final class ReorderHolder extends RecyclerView.ViewHolder {
        final View card;
        final ImageView icon;
        final TextView name;

        ReorderHolder(View v, TileListener listener, boolean animations, boolean advancedEffects, boolean reducedMotion) {
            super(v);
            card = v.findViewById(R.id.card);
            icon = v.findViewById(R.id.icon);
            name = v.findViewById(R.id.name);

            // Keeps Left, Right and Down on the row: past the Reorder tile there is nothing, and the focus search would
            // otherwise jump to the top bar.
            card.setOnKeyListener((view, keyCode, event) -> {
                if (event.getAction() != KeyEvent.ACTION_DOWN) return false;
                if (keyCode != KeyEvent.KEYCODE_DPAD_UP && keyCode != KeyEvent.KEYCODE_DPAD_DOWN
                        && keyCode != KeyEvent.KEYCODE_DPAD_LEFT && keyCode != KeyEvent.KEYCODE_DPAD_RIGHT) return false;
                int pos = getBindingAdapterPosition();
                return listener != null && pos != RecyclerView.NO_POSITION && listener.onTileVerticalKey(pos, keyCode);
            });

            card.setOnFocusChangeListener((view, focused) -> {
                view.animate().cancel();
                name.animate().cancel();
                TitleScroller.set(name, focused);
                icon.setColorFilter(focused ? 0xFF1F1F21 : 0xFFFFFFFF);
                name.setTextColor(focused ? 0xFF1F1F21 : 0xFFFFFFFF);
                float scale = 1.06f;
                float s = focused ? scale : 1f;
                if (!animations) {
                    view.setScaleX(1f);
                    view.setScaleY(1f);
                    name.setAlpha(focused ? 1f : 0.85f);
                } else if (reducedMotion) {
                    view.animate().scaleX(s).scaleY(s)
                            .setDuration(focused ? Motion.REDUCED_MS : 60)
                            .setInterpolator(new DecelerateInterpolator())
                            .start();
                    name.setAlpha(focused ? 1f : 0.85f);
                } else {
                    view.animate().scaleX(s).scaleY(s)
                            .setDuration(focused ? 220 : 170)
                            .setInterpolator(new DecelerateInterpolator(1.5f))
                            .withLayer().start();
                    name.animate().alpha(focused ? 1f : 0.85f)
                            .setDuration(220).start();
                }
                int pos = getBindingAdapterPosition();
                if (focused && listener != null && pos != RecyclerView.NO_POSITION) {
                    listener.onTileFocused(pos, view);
                }
            });

            card.setOnClickListener(v1 -> {
                if (listener != null) listener.onReorderRequested();
            });

            card.setOnKeyListener((view, keyCode, event) -> {
                if (event.getAction() != KeyEvent.ACTION_DOWN) return false;
                if (keyCode != KeyEvent.KEYCODE_DPAD_UP && keyCode != KeyEvent.KEYCODE_DPAD_DOWN
                        && keyCode != KeyEvent.KEYCODE_DPAD_LEFT && keyCode != KeyEvent.KEYCODE_DPAD_RIGHT) return false;
                int pos = getBindingAdapterPosition();
                return listener != null && pos != RecyclerView.NO_POSITION && listener.onTileVerticalKey(pos, keyCode);
            });
        }
    }
