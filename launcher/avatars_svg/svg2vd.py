"""Turns the avatar SVGs in this folder into Android vector drawables (app/src/main/res/drawable/avatar_N.xml).

Only what these SVGs use is handled: circle, ellipse, rect, line, polygon, path, <style> classes, opacity, strokes and
linear gradients (with a matrix gradientTransform). The first full circle of each file (the avatar's own background) is
left out: the launcher draws its gradient circle there instead.

    python svg2vd.py
"""
import glob
import os
import re
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, '..', 'app', 'src', 'main', 'res', 'drawable'))


def local(tag):
    return tag.split('}')[-1]


def parse_css(text):
    rules = []
    for sel, body in re.findall(r'([^{}]+)\{([^}]*)\}', text):
        props = {}
        for part in body.split(';'):
            if ':' in part:
                k, v = part.split(':', 1)
                props[k.strip()] = v.strip()
        for s in sel.split(','):
            rules.append((s.strip().lstrip('.'), props))
    return rules


def color(c):
    c = c.strip()
    if len(c) == 4 and c[0] == '#':
        c = '#' + ''.join(ch * 2 for ch in c[1:])
    return c


def num(v):
    return ('%.3f' % v).rstrip('0').rstrip('.')


def shape_path(el):
    t = local(el.tag)
    a = el.attrib
    f = lambda k, d=0.0: float(a.get(k, d))
    if t == 'path':
        return a['d']
    if t == 'circle':
        cx, cy, r = f('cx'), f('cy'), f('r')
        return 'M%s,%s a%s,%s 0 1,0 %s,0 a%s,%s 0 1,0 %s,0 Z' % (num(cx - r), num(cy), num(r), num(r), num(2 * r), num(r), num(r), num(-2 * r))
    if t == 'ellipse':
        cx, cy, rx, ry = f('cx'), f('cy'), f('rx'), f('ry')
        return 'M%s,%s a%s,%s 0 1,0 %s,0 a%s,%s 0 1,0 %s,0 Z' % (num(cx - rx), num(cy), num(rx), num(ry), num(2 * rx), num(rx), num(ry), num(-2 * rx))
    if t == 'rect':
        x, y, w, h = f('x'), f('y'), f('width'), f('height')
        return 'M%s,%s h%s v%s h%s z' % (num(x), num(y), num(w), num(h), num(-w))
    if t == 'line':
        return 'M%s,%s L%s,%s' % (num(f('x1')), num(f('y1')), num(f('x2')), num(f('y2')))
    if t == 'polygon':
        pts = [float(p) for p in re.split(r'[ ,]+', a['points'].strip())]
        out = 'M%s,%s' % (num(pts[0]), num(pts[1]))
        for i in range(2, len(pts), 2):
            out += ' L%s,%s' % (num(pts[i]), num(pts[i + 1]))
        return out + ' Z'
    return None


def gradients(root):
    grads = {}
    for g in root.iter():
        if local(g.tag) != 'linearGradient':
            continue
        m = (1, 0, 0, 1, 0, 0)
        tr = g.attrib.get('gradientTransform')
        if tr:
            m = tuple(float(x) for x in re.findall(r'-?[\d.]+', tr))
        x1, y1, x2, y2 = (float(g.attrib[k]) for k in ('x1', 'y1', 'x2', 'y2'))
        ap = lambda x, y: (m[0] * x + m[2] * y + m[4], m[1] * x + m[3] * y + m[5])
        (x1, y1), (x2, y2) = ap(x1, y1), ap(x2, y2)
        stops = [(float(s.attrib['offset']), color(s.attrib['stop-color'])) for s in g if local(s.tag) == 'stop']
        grads[g.attrib['id']] = (x1, y1, x2, y2, stops)
    return grads


def convert(svg_path):
    root = ET.parse(svg_path).getroot()
    css = ''.join((s.text or '') for s in root.iter() if local(s.tag) == 'style')
    rules = parse_css(css)
    grads = gradients(root)
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- Generated by avatars_svg/svg2vd.py from %s. -->' % os.path.basename(svg_path),
             '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
             '    xmlns:aapt="http://schemas.android.com/aapt"',
             '    android:width="128dp" android:height="128dp"',
             '    android:viewportWidth="128" android:viewportHeight="128">']
    skipped_bg = False
    for el in root.iter():
        t = local(el.tag)
        if t not in ('path', 'circle', 'ellipse', 'rect', 'line', 'polygon'):
            continue
        # The background circles (the avatar's outer disc r=60 and inner circle r=48 centered at 64,64)
        # are left out: the launcher draws its own clean gradient circle behind the character.
        if t == 'circle' and el.attrib.get('cx') == '64' and el.attrib.get('cy') == '64' and el.attrib.get('r') in ('60', '48'):
            continue
        props = {}
        for cls in el.attrib.get('class', '').split():
            for name, p in rules:
                if name == cls:
                    props.update(p)
        d = shape_path(el)
        fill = props.get('fill', '#000000')
        alpha = float(props.get('opacity', '1'))
        attrs = ['android:pathData="%s"' % d]
        gradient = None
        if fill.startswith('url('):
            gradient = grads[re.search(r'#([^)]+)', fill).group(1)]
        elif fill != 'none':
            attrs.append('android:fillColor="%s"' % color(fill))
            if alpha < 1:
                attrs.append('android:fillAlpha="%s"' % num(alpha))
        if 'stroke' in props and props['stroke'] != 'none':
            attrs.append('android:strokeColor="%s"' % color(props['stroke']))
            attrs.append('android:strokeWidth="%s"' % num(float(props.get('stroke-width', '1').replace('px', ''))))
            if alpha < 1:
                attrs.append('android:strokeAlpha="%s"' % num(alpha))
            if 'stroke-linecap' in props:
                attrs.append('android:strokeLineCap="%s"' % props['stroke-linecap'])
            if 'stroke-linejoin' in props:
                attrs.append('android:strokeLineJoin="%s"' % props['stroke-linejoin'])
            if 'stroke-miterlimit' in props:
                attrs.append('android:strokeMiterLimit="%s"' % props['stroke-miterlimit'])
        if gradient is None:
            lines.append('    <path ' + ' '.join(attrs) + ' />')
        else:
            x1, y1, x2, y2, stops = gradient
            lines.append('    <path ' + ' '.join(attrs) + '>')
            lines.append('        <aapt:attr name="android:fillColor">')
            lines.append('            <gradient android:type="linear" android:startX="%s" android:startY="%s" android:endX="%s" android:endY="%s">'
                         % (num(x1), num(y1), num(x2), num(y2)))
            for off, col in stops:
                lines.append('                <item android:offset="%s" android:color="%s" />' % (num(off), col))
            lines.append('            </gradient>')
            lines.append('        </aapt:attr>')
            lines.append('    </path>')
    lines.append('</vector>')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    for svg in sorted(glob.glob(os.path.join(HERE, 'avatar_*.svg'))):
        name = os.path.splitext(os.path.basename(svg))[0]
        with open(os.path.join(OUT, name + '.xml'), 'w', encoding='utf-8', newline='\n') as f:
            f.write(convert(svg))
        print('wrote', name + '.xml')
